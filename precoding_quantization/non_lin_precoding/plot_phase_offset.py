"""Figure of Sec. VI-F (inter-AP phase misalignment) from exp_results/phase_offset_eval.json: K = 2, the configuration
of the over-the-air experiment, SNR = 20 dB. Baseline: IDE with calibrated beta (BASE; the earlier version showed
WMMSE + DAC, 'wmmse_dac', which stays in the json), reference: unquantized WMMSE.

Grouped bar chart in the style of Fig. 7 of arXiv:2606.23141: one group per misalignment level sigma_theta
(SIGMAS), inside each group the IDE/GNN pairs for b = 1, 2, 3 and the unquantized WMMSE reference.
  bar height   Monte Carlo mean sum rate
  error bar    +- the offset-induced standard deviation for a fixed channel, sqrt(E_H[Var_theta(R | H)])
Method = fill pattern, redundant with color (as in Fig. tp_evm_cdf) for color-vision deficiency: GNN solid, IDE
diagonal hatching, unquantized WMMSE horizontal hatching on white; shade = b (light -> dark); method-by-resolution
legend matrix.
The kappa model and the former panel (c) (relative loss versus SNR) are not drawn; their data stay in the json.

  python plot_phase_offset.py [out.tex]     # default: the paper's Figure/rsum_phase_offset.tex
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, 'exp_results', 'phase_offset_eval.json')
OUT = '/home/user/Quantized-aware-training-and-deploy-study/Figure/rsum_phase_offset.tex'
K = 2
SNR_A = 20.0
BASE = 'ide_cal'
SIGMAS = (0.0, 10.0, 20.0, 30.0)               # misalignment levels shown as groups [deg]
AXIS_W_CM = 6.9                                  # must match 'width' in HEAD
BAR_W, PAIR_GAP = 4.4, 2.6                       # bar width and gap between the b pairs [pt]
SHADE = {1: 35, 2: 65, 3: 100}                   # fill = <method color>!SHADE!white

HEAD = r"""% Mean sum rate under inter-AP phase misalignment theta_m, i.i.d. over the APs, theta_m ~ N(0, sigma_theta^2),
% constant over a block and unknown to the precoder (Sec. VI-F); M = 40, K = 2, SNR = 20 dB; precoders trained with
% sigma_theta = 0. Grouped bars in the style of Fig. 7 of arXiv:2606.23141.
% Bars: Monte Carlo mean; error bars: +- the offset-induced standard deviation sqrt(E_H[Var_theta(R | H)]).
% Method = pattern (GNN solid, IDE diagonal hatching, unquantized WMMSE horizontal hatching), redundant with the
% colors of evm_cdf_comparison.tex; shade = b (light 1 bit -> full 3 bits).
% IDE with calibrated beta: Wang et al., TWC 2018; beta calibrated per channel and SNR on an independent block of
% 125 Gaussian symbol vectors.
% Data: exp_results/phase_offset_eval.json (phase_offset_eval.py): 2048 held-out channels (Htest[4096:6144]),
% {n} offset draws per channel, LS Bussgang estimator; sigma_theta = 0 reproduces Figs. 3 and 4.
% Generated by plot_phase_offset.py.
\documentclass[tikz,border=4pt]{{standalone}}
\usepackage[T1]{{fontenc}}
\usepackage{{newtxtext,newtxmath}}
\usepackage{{pgfplots}}
\pgfplotsset{{compat=1.18}}
\usetikzlibrary{{matrix,calc,patterns.meta}}
\begin{{document}}
\definecolor{{poGNN}}{{HTML}}{{004488}}%
\definecolor{{poIDE}}{{HTML}}{{BB5566}}%
\definecolor{{poRef}}{{HTML}}{{555555}}%
\definecolor{{poGrid}}{{HTML}}{{E2E5E8}}%
\definecolor{{poInk}}{{HTML}}{{42484F}}%
\pgfplotsset{{%
  po/bar/.style={{
    ybar, bar width={w}pt, bar shift=0pt, line width=0.4pt, forget plot,
    error bars/.cd, y dir=both, y explicit,
    error bar style={{black!70, line width=0.5pt}},
    error mark options={{rotate=90, mark size=1.4pt, black!70, line width=0.5pt}},
  }},
}}%
\tikzset{{%  method patterns, also used by the legend swatches
  ide hatch/.style={{postaction={{pattern={{Lines[angle=45, distance=1.8pt, line width=0.45pt]}}, pattern color=poIDE!45!black}}}},
  ref hatch/.style={{postaction={{pattern={{Lines[angle=0, distance=1.6pt, line width=0.45pt]}}, pattern color=poRef}}}},
}}%
\begin{{tikzpicture}}
\begin{{axis}}[
  name=po,
  scale only axis, width=6.9cm, height=5.6cm,
  axis lines=left, axis line style={{draw=poInk, line width=0.45pt, -}},
  tick align=outside, tick pos=left,
  major tick length=2.5pt, tick style={{draw=poInk, line width=0.45pt}},
  ymajorgrids=true, xmajorgrids=false,
  grid style={{line width=0.3pt, draw=poGrid}},
  tick label style={{font=\footnotesize, /pgf/number format/fixed}},
  label style={{font=\small}},
  xlabel={{Phase misalignment $\sigma_\theta$}}, ylabel={{Mean $R_{{\mathrm{{sum}}}}$ [bits/channel use]}},
  xmin=0.45, xmax={xmax}, xtick={{{xt}}}, xticklabels={{{xtl}}}, x tick style={{draw=none}},
  ymin=0, ymax=29, ytick={{0,5,10,15,20,25}},
]
"""

LEGEND = r"""% Method-by-resolution legend in the empty upper right, as in Fig. tp_evm_cdf.
\matrix [
    draw=black!25, line width=0.35pt, fill=white, rounded corners=1.5pt,
    anchor=north east, font=\scriptsize, inner sep=2.5pt, row sep=2pt, column sep=2pt,
    column 1/.style={nodes={inner sep=1pt, anchor=west}},
    column 2/.style={nodes={inner sep=0pt, minimum width=1.2em, anchor=center}},
    column 3/.style={nodes={inner sep=0pt, minimum width=1.2em, anchor=center}},
    column 4/.style={nodes={inner sep=0pt, minimum width=1.2em, anchor=center}}
] (poLegend) at ([xshift=-3pt, yshift=-3pt] po.north east) {
    \node[font=\scriptsize\bfseries, text=black!60] {Method}; &
    \node[font=\scriptsize\bfseries, text=black!60] (poB1) {$1$\,b}; &
    \node[font=\scriptsize\bfseries, text=black!60] {$2$\,b}; &
    \node[font=\scriptsize\bfseries, text=black!60] (poB3) {$3$\,b}; \\
    \node[text=poGNN, font=\scriptsize\bfseries] {GNN (Prop.)}; &
    \draw[fill=poGNN!35!white, draw=poGNN, line width=0.4pt] (-0.1,-0.07) rectangle (0.1,0.07); &
    \draw[fill=poGNN!65!white, draw=poGNN, line width=0.4pt] (-0.1,-0.07) rectangle (0.1,0.07); &
    \draw[fill=poGNN, draw=poGNN, line width=0.4pt] (-0.1,-0.07) rectangle (0.1,0.07); \\
    \node[text=black!85] {IDE, cal.\ $\beta$}; &
    \draw[fill=poIDE!35!white, draw=poIDE, line width=0.4pt, ide hatch] (-0.1,-0.07) rectangle (0.1,0.07); &
    \draw[fill=poIDE!65!white, draw=poIDE, line width=0.4pt, ide hatch] (-0.1,-0.07) rectangle (0.1,0.07); &
    \draw[fill=poIDE, draw=poIDE, line width=0.4pt, ide hatch] (-0.1,-0.07) rectangle (0.1,0.07); \\[3pt]
    \node[text=black!75] (poUnq) {Unquantized WMMSE}; & & & \\
};
\draw[black!20, line width=0.3pt]
    ($(poLegend.west |- poUnq.north)+(3.3pt,2.7pt)$) -- ($(poLegend.east |- poUnq.north)+(-3.3pt,2.7pt)$);
\draw[fill=white, draw=poRef, line width=0.4pt, ref hatch]
    ($(poB3 |- poUnq.west)+(-0.1,-0.07)$) rectangle ($(poB3 |- poUnq.west)+(0.1,0.07)$);
"""

COLOR = {'gnn': 'poGNN', BASE: 'poIDE', 'wmmse_unq': 'poRef'}
PATTERN = {'gnn': '', BASE: ', ide hatch', 'wmmse_unq': ', ref hatch'}   # method = pattern (before po/bar, which ends in error bars/.cd)


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else OUT
    J = json.load(open(SRC))
    S, X = J['sigma_deg'], J['snr_db']
    ja = X.index(SNR_A)
    R = {b: J['results'][f'K{K}b{b}']['methods'] for b in (1, 2, 3)}
    idx = [S.index(s) for s in SIGMAS]

    def val(b, m, k, i):
        return R[b][m][k][i][ja]

    # Bars of one group, left to right: (IDE, GNN) for b = 1, 2, 3, then the unquantized reference.
    series = [(BASE, 1), ('gnn', 1), (BASE, 2), ('gnn', 2), (BASE, 3), ('gnn', 3), ('wmmse_unq', 1)]
    gaps = [0, 0, PAIR_GAP, 0, PAIR_GAP, 0, PAIR_GAP]
    centers, x = [], 0.0
    for g in gaps:
        x += g
        centers.append(x + BAR_W / 2)
        x += BAR_W
    mid = x / 2
    shifts = [c - mid for c in centers]

    n = len(SIGMAS)
    # Each bar is placed at its own x coordinate (bar shift 0), so that its error bar is centered on it.
    unit_pt = AXIS_W_CM * 72.27 / 2.54 / (n + 0.55 - 0.45)        # axis units -> pt
    head = HEAD.format(n=J['n_theta'], w=BAR_W, xmax=f'{n + 0.55:g}',
                       xt=','.join(str(g + 1) for g in range(n)),
                       xtl=','.join(f'${s:g}^\\circ$' for s in SIGMAS))
    L = [head.rstrip('\n')]
    for (m, b), sh in zip(series, shifts):
        fill = 'white' if m == 'wmmse_unq' else f'{COLOR[m]}!{SHADE[b]}!white'
        name = 'unquantized WMMSE' if m == 'wmmse_unq' else f'{m}, b = {b}'
        rows = [f'{g + 1 + sh / unit_pt:.4f} {val(b, m, "mean", i):.4f} {val(b, m, "std_offset", i):.4f}'
                for g, i in enumerate(idx)]
        L += [f'% {name}',
              r'\addplot[fill=%s, draw=%s%s, po/bar] table[x index=0, y index=1, y error index=2] {%%'
              % (fill, COLOR[m], PATTERN[m])] + rows + ['};']
    L += [r'\end{axis}', LEGEND.rstrip('\n'), r'\end{tikzpicture}', r'\end{document}', '']
    open(out, 'w').write('\n'.join(L))
    print('wrote', out)


if __name__ == '__main__':
    main()
